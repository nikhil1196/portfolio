<?php
require_once dirname(__DIR__) . '/_core/boot.php';
$app = app_boot(__DIR__);
auth_require($app);
$tickets = ['' => '— Ticket —'] + array_column(qa($app, "SELECT id, ticket_no||' · '||subject AS n FROM tickets ORDER BY id DESC"), 'n', 'id');
crud_page($app, [
    'title' => 'Reply', 'table' => 'replies',
    'fields' => [
        ['name'=>'id','label'=>'','type'=>'hidden'],
        ['name'=>'ticket_id','label'=>'Ticket','type'=>'select','options'=>$tickets,'required'=>true],
        ['name'=>'author','label'=>'Author','required'=>true],
        ['name'=>'body','label'=>'Reply','type'=>'textarea','required'=>true],
        ['name'=>'is_ai','label'=>'Generated by AI','type'=>'select','options'=>[0=>'No',1=>'Yes']],
    ],
    'list_sql' => 'SELECT r.*, t.ticket_no, t.subject FROM replies r LEFT JOIN tickets t ON t.id=r.ticket_id ORDER BY r.id DESC',
    'columns' => [
        'Ticket' => fn($r) => '<code>' . h($r['ticket_no']) . '</code><br><span class="note">' . h(mb_strimwidth($r['subject'] ?? '', 0, 40, '…')) . '</span>',
        'Author' => fn($r) => '<strong>' . h($r['author']) . '</strong>' . ($r['is_ai'] ? ' ' . status_badge('AI') : ''),
        'Reply'  => fn($r) => h(mb_strimwidth($r['body'] ?? '', 0, 90, '…')),
        'Sent'   => fn($r) => dt($r['created_at'], 'd M, h:i A'),
    ],
]);
